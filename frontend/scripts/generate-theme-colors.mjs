// 由 tokens.css 里的基础色推出 Element Plus 的 --el-color-*-light-N / dark-2 及几个中性色，写回 tokens.css 的标记区间。
// 规则（见 docs/ui_design.md 第 2 节）：light-N = 色与单据纸按 N×10% 混合（套色的浅色都是墨和纸调出来的，不掺白），dark-2 = 色与黑按 20% 混合。
// 用法：
//   node scripts/generate-theme-colors.mjs           打印生成的区间
//   node scripts/generate-theme-colors.mjs --write   写回 tokens.css
//   node scripts/generate-theme-colors.mjs --check   与 tokens.css 现有内容比对，不一致则退出码 1
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const tokensPath = resolve(dirname(fileURLToPath(import.meta.url)), '../src/styles/tokens.css')
const START = '  /* >>> generated by scripts/generate-theme-colors.mjs, do not edit by hand >>> */'
const END = '  /* <<< generated <<< */'

const hex = (n) => n.toString(16).padStart(2, '0')
const parse = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
const toHex = (rgb) => `#${rgb.map(hex).join('')}`
// 把 color 与 other 按 other 占 weight 混合
const mix = (color, other, weight) => {
  const a = parse(color)
  const b = parse(other)
  return toHex(a.map((c, i) => Math.round(c * (1 - weight) + b[i] * weight)))
}

const css = readFileSync(tokensPath, 'utf8')
const base = (name) => {
  const m = css.match(new RegExp(`--eas-${name}:\\s*(#[0-9a-fA-F]{6})\\s*;`))
  if (!m) throw new Error(`tokens.css 里找不到 --eas-${name}`)
  return m[1].toLowerCase()
}

const PAPER = base('sheet')
const BLACK = '#000000'
const lines = []
const scale = (el, color) => {
  lines.push(`  --el-color-${el}: ${color};`)
  lines.push(`  --el-color-${el}-rgb: ${parse(color).join(', ')};`)
  for (const n of [3, 5, 7, 8, 9]) lines.push(`  --el-color-${el}-light-${n}: ${mix(color, PAPER, n / 10)};`)
  lines.push(`  --el-color-${el}-dark-2: ${mix(color, BLACK, 0.2)};`)
}
scale('primary', base('primary'))
scale('success', base('success'))
scale('warning', base('warning'))
scale('danger', base('danger'))
scale('error', base('danger'))
scale('info', base('muted'))

// 中性色：由 ink-3 / rule-strong / row-hover / desk 推出
const ruleStrong = base('rule-strong')
const rowHover = base('row-hover')
const desk = base('desk')
lines.push(`  --el-text-color-disabled: ${mix(base('ink-3'), PAPER, 0.4)};`)
lines.push(`  --el-border-color-dark: ${mix(ruleStrong, BLACK, 0.1)};`)
lines.push(`  --el-border-color-darker: ${mix(ruleStrong, BLACK, 0.2)};`)
lines.push(`  --el-fill-color-lighter: ${mix(rowHover, PAPER, 0.5)};`)
lines.push(`  --el-fill-color-extra-light: ${mix(rowHover, PAPER, 0.75)};`)
lines.push(`  --el-mask-color: rgba(${parse(desk).join(', ')}, 0.8);`)

const block = [START, ...lines, END].join('\n')

const startAt = css.indexOf(START)
const endAt = css.indexOf(END)
const current = startAt >= 0 && endAt > startAt ? css.slice(startAt, endAt + END.length) : null
const mode = process.argv[2]

if (mode === '--write') {
  if (current === null) throw new Error('tokens.css 里缺少 generated 标记区间')
  writeFileSync(tokensPath, css.replace(current, block))
  console.log('tokens.css 已更新')
} else if (mode === '--check') {
  if (current !== block) {
    console.error('tokens.css 的生成区间已过期，请运行 node scripts/generate-theme-colors.mjs --write')
    process.exit(1)
  }
  console.log('tokens.css 的生成区间是最新的')
} else {
  console.log(block)
}
